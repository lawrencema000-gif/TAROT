/**
 * Display-sized sources for the appearance images: the card back and the
 * painted background a profile stores.
 *
 * The stock card back in Storage is a 2.6 MB 1024×1536 PNG and the seven
 * backgrounds are 2.8–9.6 MB PNGs, all served `max-age=0`. Every account
 * created before Phase 7 was given one of each automatically, so every cold
 * open re-downloaded ~5–12 MB to paint a 96px card and a background under an
 * 85% scrim, and the deck drew top-down while the PNG streamed. The stored
 * URL is the member's choice and is never rewritten; only what is fetched
 * for it changes:
 *
 *   - the stock files have WebP renditions shipped in public/ (generated by
 *     scripts/appearance-renditions.py, long-cached by _headers), keyed by
 *     the stored file name;
 *   - any other file in those Storage buckets goes through Supabase's image
 *     transform endpoint (enabled on this project; checked 2026-10-03),
 *     scaled to a width at its own aspect (see transformUrl);
 *   - the bundled tarot images use their existing 150/400 renditions;
 *   - anything else (the default SVG, a data: URL) is used as given.
 */

export const DEFAULT_CARD_BACK = '/card-backs/default.svg';

/** Card-back rendition widths in public/card-backs/r/ (px). */
export const CARD_BACK_WIDTHS = [200, 480] as const;
/** Background rendition width in public/backgrounds/full/ (px). */
export const BACKGROUND_WIDTH = 900;

/** Stored file stems with shipped renditions. Keep in step with the script. */
const STOCK_CARD_BACKS = new Set(['card_back_1768047025411']);
const STOCK_BACKGROUNDS = new Set([
  'background_1768048475356',
  'background_1768048480582',
  'background_1768048488103',
  'background_1768048493449',
  'background_1768048497998',
  'background_1768048502487',
  'background_1768048506937',
]);

const STORAGE_RE = /^(https:\/\/[^/]+\.supabase\.co)\/storage\/v1\/object\/public\/(card-backs|backgrounds)\/([^?#]+)(?:[?#].*)?$/;
const BUNDLED_CARD_RE = /^\/bundled-cards\/(major-arcana|minor-arcana)\/([^/]+\.webp)$/;

export interface ImageSources {
  src: string;
  srcSet?: string;
  sizes?: string;
}

function stemOf(path: string): string {
  const file = path.split('/').pop() ?? '';
  return file.replace(/\.[a-z0-9]+$/i, '');
}

/**
 * Supabase's image transform for a stored file, `width` px wide at its own
 * aspect. `resize=contain` is not optional: the endpoint's default mode is
 * `cover`, and `cover` with a width alone keeps the source's full height, so
 * a 1024×1536 back asked for at width 200 came back 200×1536 — a strip of
 * the middle of the art, which the card then cropped again (p8 F45).
 * Exported for the geometry check (imageUrl.geometry.test.ts).
 */
export function transformUrl(origin: string, bucket: string, path: string, width: number, quality: number): string {
  return `${origin}/storage/v1/render/image/public/${bucket}/${path}?width=${width}&quality=${quality}&resize=contain`;
}

/** The narrowest width in `widths` that covers `need` px, else the widest. */
function pick(widths: readonly number[], need: number): number {
  return widths.find((w) => w >= need) ?? widths[widths.length - 1];
}

/**
 * `<img>` sources for a card back drawn `cssWidth` px wide: `src` covers 2×
 * on its own, `srcSet` + `sizes` let the browser take less on a 1× screen.
 */
export function cardBackSources(url: string | null | undefined, cssWidth: number): ImageSources {
  const src = url || DEFAULT_CARD_BACK;
  const sizes = `${Math.round(cssWidth)}px`;

  const bundled = BUNDLED_CARD_RE.exec(src);
  if (bundled) {
    const thumb = `/bundled-cards/thumb/${bundled[1]}/${bundled[2]}`;
    const full = `/bundled-cards/full/${bundled[1]}/${bundled[2]}`;
    return {
      src: cssWidth * 2 <= 150 ? thumb : cssWidth * 2 <= 400 ? full : src,
      srcSet: `${thumb} 150w, ${full} 400w, ${src} 512w`,
      sizes,
    };
  }

  const stored = STORAGE_RE.exec(src);
  if (stored && stored[2] === 'card-backs') {
    const [, origin, bucket, path] = stored;
    const stem = stemOf(path);
    const at = (w: number) =>
      STOCK_CARD_BACKS.has(stem) ? `/card-backs/r/${stem}-${w}.webp` : transformUrl(origin, bucket, path, w, 75);
    return {
      src: at(pick(CARD_BACK_WIDTHS, cssWidth * 2)),
      srcSet: CARD_BACK_WIDTHS.map((w) => `${at(w)} ${w}w`).join(', '),
      sizes,
    };
  }

  return { src };
}

/** One card-back URL for a `cssWidth`-px card at 2× (for CSS backgrounds and plain `src`). */
export function cardBackSrc(url: string | null | undefined, cssWidth: number): string {
  return cardBackSources(url, cssWidth).src;
}

/** The full-bleed background for a stored background URL. */
export function backgroundSrc(url: string): string {
  const stored = STORAGE_RE.exec(url);
  if (!stored || stored[2] !== 'backgrounds') return url;
  const [, origin, bucket, path] = stored;
  const stem = stemOf(path);
  return STOCK_BACKGROUNDS.has(stem)
    ? `/backgrounds/full/${stem}.webp`
    : transformUrl(origin, bucket, path, BACKGROUND_WIDTH, 55);
}
